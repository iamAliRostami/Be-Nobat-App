tsv_path = os.path.join("src", "BeNobat.Web", "Resources", "WebTranslations.tsv")
with open(tsv_path, "r", encoding="utf-8") as f:
    lines = f.readlines()

existing_fa = set()
for line in lines:
    parts = line.strip().split("\t")
    if parts:
        existing_fa.add(parts[0].strip())

added = 0
with open(tsv_path, "a", encoding="utf-8") as f:
    for fa, en, ar in new_entries:
        if fa.strip() not in existing_fa:
            f.write(f"{fa.strip()}\t{en.strip()}\t{ar.strip()}\n")
            existing_fa.add(fa.strip())
            added += 1

print(f"Added {added} new translations to {tsv_path}")
